import mongoose, { Schema } from "mongoose";

/**
 * Admin Management governance for the Nexura admin dashboard (platform admins). Same rules as the
 * Studio's hub governance (models/governance.model.ts), kept in its own collections so the two never mix.
 *
 * - The Owner (ownerId) is always a signer.
 * - Super Admins become signers only through an approved proposal.
 * - Every proposal, vote and execution is an EIP-712 signature from the admin's linked wallet.
 */
const platformGovernanceSchema = new Schema({
	// Single document for the platform
	key: { type: String, default: "platform", unique: true },
	ownerId: { type: Schema.Types.ObjectId, ref: "admin", default: null },
	// PLATFORM_OWNER_EMAIL already applied; set once so a later ownership transfer isn't undone
	ownerSeedEmail: { type: String, default: "" },
	// Super Admins added as signers (the Owner is implicit and never listed)
	signers: [{ type: Schema.Types.ObjectId, ref: "admin" }],
}, { timestamps: true });

const signatureSchema = new Schema({
	admin: { type: Schema.Types.ObjectId, ref: "admin", required: true },
	name: { type: String, default: "" },
	kind: { type: String, enum: ["propose", "approve", "reject", "execute"], required: true },
	address: { type: String, required: true },
	signature: { type: String, required: true },
	scheme: { type: String, enum: ["typed", "text"], default: "typed" },
	message: { type: Schema.Types.Mixed, required: true },
	signedAt: { type: Date, required: true },
}, { _id: false });

const platformProposalSchema = new Schema({
	// Id generated by the client before signing, so it can be part of the signed data
	ref: { type: String, required: true, unique: true },
	title: { type: String, required: true },
	change: { type: String, default: "" },
	action: { type: Schema.Types.Mixed, required: true },
	proposedBy: {
		id: { type: Schema.Types.ObjectId, ref: "admin", required: true },
		name: { type: String, default: "" },
	},
	signatures: [signatureSchema],
	status: { type: String, enum: ["pending", "executed", "rejected"], default: "pending", index: true },
	resolvedAt: { type: Date, default: null },
	resolvedCount: { type: Number, default: null },
	executionError: { type: String, default: null },
	executingAt: { type: Date, default: null },
	readBy: [{ type: Schema.Types.ObjectId, ref: "admin" }],
	// Executed invite whose email couldn't be delivered: the code for a signer to pass on
	inviteShare: {
		type: new Schema({ link: String, code: String, emailError: String }, { _id: false }),
		default: null,
	},
}, { timestamps: true });

export const platformGovernance = mongoose.model("platform-governance", platformGovernanceSchema);
export const platformProposal = mongoose.model("platform-governance-proposals", platformProposalSchema);
