import mongoose, { Schema } from "mongoose";

/**
 * Studio governance (Admin Management), modelled on a Safe multisig.
 *
 * - The hub Owner (hub.superAdmin) is always a signer.
 * - Super Admins become signers only through an approved proposal.
 * - Every proposal, vote and execution is an EIP-712 signature from the admin's linked wallet.
 */
const hubGovernanceSchema = new Schema({
	hub: {
		type: Schema.Types.ObjectId,
		ref: "hubs",
		required: true,
		unique: true,
	},
	// null = every signer
	approvalThreshold: { type: Number, default: null },
	rejectionThreshold: { type: Number, default: null },
	// Super Admins added as signers (the Owner is implicit and never listed)
	signers: [{ type: Schema.Types.ObjectId, ref: "hub-admins" }],
	// adminId -> wallet address, linked on the admin's first signature
	signerWallets: { type: Map, of: String, default: {} },
}, { timestamps: true });

const governanceSignatureSchema = new Schema({
	admin: { type: Schema.Types.ObjectId, ref: "hub-admins", required: true },
	name: { type: String, default: "" },
	kind: { type: String, enum: ["propose", "approve", "reject", "execute"], required: true },
	address: { type: String, required: true },
	signature: { type: String, required: true },
	scheme: { type: String, enum: ["typed", "text"], default: "typed" },
	message: { type: Schema.Types.Mixed, required: true },
	signedAt: { type: Date, required: true },
}, { _id: false });

const governanceProposalSchema = new Schema({
	hub: { type: Schema.Types.ObjectId, ref: "hubs", required: true, index: true },
	// Id generated by the client before signing, so it can be part of the signed data
	ref: { type: String, required: true },
	title: { type: String, required: true },
	change: { type: String, default: "" },
	action: { type: Schema.Types.Mixed, required: true },
	proposedBy: {
		id: { type: Schema.Types.ObjectId, ref: "hub-admins", required: true },
		name: { type: String, default: "" },
	},
	signatures: [governanceSignatureSchema],
	status: { type: String, enum: ["pending", "executed", "rejected"], default: "pending" },
	resolvedAt: { type: Date, default: null },
	resolvedCount: { type: Number, default: null },
	executionError: { type: String, default: null },
	executingAt: { type: Date, default: null },
	// Admins who marked this proposal's notification as read
	readBy: [{ type: Schema.Types.ObjectId, ref: "hub-admins" }],
	// Executed invite whose email couldn't be delivered: the link and code for a signer to pass on
	inviteShare: {
		type: new Schema({ link: String, code: String, emailError: String }, { _id: false }),
		default: null,
	},
}, { timestamps: true });

governanceProposalSchema.index({ hub: 1, ref: 1 }, { unique: true });

export const hubGovernance = mongoose.model("hub-governance", hubGovernanceSchema);
export const governanceProposal = mongoose.model("governance-proposals", governanceProposalSchema);
